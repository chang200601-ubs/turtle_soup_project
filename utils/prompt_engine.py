import random

_CANARY_POOL = [
    "彩虹獨角獸", "紫色章魚", "飛天鯊魚", "水晶蜥蜴",
    "霓虹北極熊", "透明企鵝", "旋轉烏龜", "發光犰狳",
    "磁浮貓咪",   "量子河馬", "超導蜜蜂", "反重力狐狸",
]

_current_canary: str = ""


def get_canary() -> str:
    global _current_canary
    if not _current_canary:
        _current_canary = random.choice(_CANARY_POOL)
    return _current_canary


def reset_canary():
    global _current_canary
    _current_canary = random.choice(_CANARY_POOL)


